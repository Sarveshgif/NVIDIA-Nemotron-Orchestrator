"""Regenerate src/data/dwrFields.ts from DWR 2023 Statewide Crop Mapping.

Pulls every Tulare County polygon whose season-2 crop is corn (CROPTYP2 = 'F16'),
and keeps the 12 largest single-part fields >= 15 acres whose centroid falls in each
~2.4 x 2 km cluster window below. Standard library only:

    python3 scripts/fetch-dwr-fields.py
"""
import json, urllib.parse, urllib.request

SERVICE = ("https://utility.arcgis.com/usrsvcs/servers/d94e891e00364e49a2ed9e9e2e27837d"
           "/rest/services/Planning/i15_Crop_Mapping_2023/MapServer/0/query")
W, H = 0.027, 0.018  # window size in degrees (lng, lat)
PER_CLUSTER, MIN_ACRES = 12, 15
# North-west corner (lat, lng) of each cluster window. Picked as dense corn areas,
# spread across the valley floor: A west of Visalia, B east of Tulare, C near Traver, D near Pixley.
WINDOWS = {'A': (36.25, -119.445), 'B': (36.15, -119.295), 'C': (36.435, -119.35), 'D': (35.925, -119.34)}


def fetch():
    feats, off = [], 0
    while True:
        q = dict(f='json', where="CROPTYP2='F16' AND COUNTY='Tulare'", outSR=4326,
                 outFields='UniqueID,ACRES', returnGeometry='true', geometryPrecision=6,
                 resultOffset=off, resultRecordCount=1000, orderByFields='OBJECTID')
        d = json.load(urllib.request.urlopen(SERVICE, data=urllib.parse.urlencode(q).encode(), timeout=180))
        if 'error' in d:
            raise SystemExit(d['error'])
        feats += d['features']
        if len(d['features']) < 1000:
            return feats
        off += 1000


def centroid(ring):
    return sum(p[1] for p in ring) / len(ring), sum(p[0] for p in ring) / len(ring)


def main():
    good = []
    for f in fetch():
        rings = f['geometry']['rings']
        if len(rings) == 1 and f['attributes']['ACRES'] >= MIN_ACRES:
            good.append((f, centroid(rings[0])))

    def inside(la, lg):
        return [g for g in good if la - H <= g[1][0] <= la and lg <= g[1][1] <= lg + W]

    rows = []
    for label, (la, lg) in WINDOWS.items():
        sel = sorted(inside(la, lg), key=lambda g: -g[0]['attributes']['ACRES'])[:PER_CLUSTER]
        sel.sort(key=lambda g: (-round(g[1][0], 3), g[1][1]))  # north to south, west to east
        for f, _ in sel:
            ring = f['geometry']['rings'][0]
            if ring[0] == ring[-1]:
                ring = ring[:-1]
            pts = json.dumps([[round(p[1], 6), round(p[0], 6)] for p in ring], separators=(',', ':'))
            rows.append(f"  {{ cluster: '{label}', dwrId: '{f['attributes']['UniqueID']}', ring: {pts} }},")

    header = [
        "// Real corn field boundaries from the California DWR 2023 Statewide Crop Mapping",
        "// (i15_Crop_Mapping_2023, Land IQ for DWR), Tulare County, fields with season-2 crop F16 (corn).",
        "// Source: https://data.cnra.ca.gov/dataset/statewide-crop-mapping",
        "// F16 groups corn, sorghum and sudan. Time series for these fields come from scripts/fetch-sentinel.py.",
        "// Generated by scripts/fetch-dwr-fields.py. Rings are [lat, lng].",
        "",
        "export interface SourceField { cluster: string; dwrId: string; ring: [number, number][] }",
        "",
        "export const DWR_FIELDS: SourceField[] = [",
    ]
    with open('src/data/dwrFields.ts', 'w') as fh:
        fh.write('\n'.join(header + rows + ['];', '']))
    print(f'wrote {len(rows)} fields')


if __name__ == '__main__':
    main()
